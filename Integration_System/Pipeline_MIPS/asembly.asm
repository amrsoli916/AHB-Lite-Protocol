# =========================
# RAM base address
# =========================
addi $t0, $zero, 0x0000

# Data
addi $t1, $zero, 0x1122
addi $t2, $zero, 0x3344

# =========================
# Write to RAM twice
# =========================
sw $t1, 0($t0)
sw $t2, 4($t0)

# =========================
# 2 ADD instructions
# =========================
add $t4, $t1, $t2
add $t5, $t1, $t2

# =========================
# UART base address
# =========================
addi $t3, $zero, 0x0400

# =========================
# Write to UART twice
# Address = 0x0404
# =========================
sw $t1, 4($t3)
sw $t2, 4($t3)

# =========================
# 2 ADD instructions
# =========================
add $t6, $t1, $t2
add $t7, $t1, $t2

# =========================
# Load from RAM twice
# =========================
lw $s0, 0($t0)
lw $s1, 4($t0)

# =========================
# 2 ADD instructions
# =========================
add $s4, $t1, $t2
add $s5, $t1, $t2

# =========================
# Load from UART twice
# Address = 0x0404
# =========================
lw $s2, 4($t3)
lw $s3, 4($t3)

# =========================
# Infinite loop
# =========================
loop:
beq $zero, $zero, loop